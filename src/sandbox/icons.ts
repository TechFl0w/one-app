/**
 * The kit's <Icon>: 1em square (so it follows the text size) unless sized by className, colour
 * from the text. Decorative unless labelled. Unknown names draw nothing (never crash).
 */
export function Icon({ name, className, label }: { name: string; className?: string; label?: string }) {
  const key = normalizeIconName(name);
  if (!isIconName(key)) return null;
  const props: LucideProps & { "data-icon": string } = {
    width: "1em",
    height: "1em",
    className: ["inline-block shrink-0 align-[-0.125em]", className].filter(Boolean).join(" "),
    "data-icon": key,
    ...(label ? { role: "img", "aria-label": label } : { "aria-hidden": true }),
  };
  return createElement(ICONS[key], props);
}
